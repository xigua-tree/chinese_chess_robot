def train_and_save_model(p_pts, w_pts, filename="map_model.npz"):
    tps = cv2.createThinPlateSplineShapeTransformer()
    ss = p_pts.reshape(1, -1, 2)
    td = w_pts.reshape(1, -1, 2)
    matches = [cv2.DMatch(i, i, 0) for i in range(len(p_pts))]
    tps.estimateTransformation(ss, td, matches)
    np.savez(filename, pixel_pts=p_pts, world_pts=w_pts)
    print(f"--- 优化版模型 (精简至 {len(p_pts)} 点) 已成功保存 ---")
    return tps

def transform_point(tps, u, v):
    pt = np.array([[[u, v]]], dtype=np.float32)
    _, transformed_pt = tps.applyTransformation(pt)
    return transformed_pt[0][0][0], transformed_pt[0][0][1]

